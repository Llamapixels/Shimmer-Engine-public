/* Move one coordinate at most `speed` px closer to `target`, clamped
 * so it never overshoots. Shared by actor_step_toward() below. */
static int step_toward(int current, int target, int speed)
{
    if (current < target)
    {
        current += speed;
        if (current > target)
            current = target;
    }
    else if (current > target)
    {
        current -= speed;
        if (current < target)
            current = target;
    }

    return current;
}

int actor_step_toward(int index, int target_x, int target_y)
{
    Entity *npc = entity_for_actor(index);
    if (!npc)
        return 0;
    if (npc->gravity)
        target_y = npc->y;   /* gravity decides up and down */

    /* X fully, then Y - same one-axis-at-a-time shape as the wander
     * movement above, since the sprite can only face one axis. */
    if (npc->x != target_x)
    {
        Direction dir = (target_x > npc->x) ? DIR_RIGHT : DIR_LEFT;
        npc->x = step_toward(npc->x, target_x, npc->move_speed ? npc->move_speed : 1);
        entity_animate(npc, dir, 1);
        return 1;
    }

    if (npc->y != target_y)
    {
        Direction dir = (target_y > npc->y) ? DIR_DOWN : DIR_UP;
        npc->y = step_toward(npc->y, target_y, npc->move_speed ? npc->move_speed : 1);
        entity_animate(npc, dir, 1);
        return 1;
    }

    entity_animate(npc, (Direction)npc->direction, 0);   /* arrived - stop */
    return 0;
}

int actor_step_toward_ex(int index, int target_x, int target_y, int type, int collide, int keep_dir)
{
    Entity *e = entity_for_actor(index);
    if (!e)
        return 0;
    if (e->gravity)
        target_y = e->y;   /* gravity decides up and down */
    int dx = target_x - e->x;
    int dy = target_y - e->y;
    if (!dx && !dy)
    {
        entity_animate(e, (Direction)e->direction, 0);   /* arrived - stop */
        return 0;
    }

    /* Which axes move this frame: diagonal = both, else one at a time
     * (horizontal or vertical first). */
    int mx = 0, my = 0;
    if (type == 2)
    {
        mx = dx;
        my = dy;
    }
    else if (type == 1)
    {
        if (dy) my = dy; else mx = dx;
    }
    else
    {
        if (dx) mx = dx; else my = dy;
    }

    int speed = e->move_speed ? e->move_speed : 1;
    int nx = mx ? step_toward(e->x, target_x, speed) : e->x;
    int ny = my ? step_toward(e->y, target_y, speed) : e->y;

    int adx = nx - e->x < 0 ? e->x - nx : nx - e->x;
    int ady = ny - e->y < 0 ? e->y - ny : ny - e->y;
    Direction dir = adx >= ady ? (nx > e->x ? DIR_RIGHT : DIR_LEFT) : (ny > e->y ? DIR_DOWN : DIR_UP);

    if (collide && walks_slopes(e) && ny == e->y)
    {
        /* Along the ground: up and down slopes, stopped by walls. */
        if (!walker_step_x(e, nx))
        {
            entity_animate(e, (Direction)e->direction, 0);   /* blocked - give up */
            return 0;
        }
        entity_animate(e, keep_dir ? (Direction)e->direction : dir, 1);
        return 1;
    }

    if (collide && !entity_can_move(e, nx, ny))
    {
        /* Diagonal: slide along whichever axis is still free. */
        if (mx && my && entity_can_move(e, nx, e->y))
            ny = e->y;
        else if (mx && my && entity_can_move(e, e->x, ny))
            nx = e->x;
        else if (slide_along_slope(e, nx, ny))
        {
            /* A diagonal wall: slid along it. */
            entity_animate(e, keep_dir ? (Direction)e->direction : dir, 1);
            return 1;
        }
        else
        {
            entity_animate(e, (Direction)e->direction, 0);   /* blocked - give up */
            return 0;
        }
    }

    e->x = nx;
    e->y = ny;
    entity_animate(e, keep_dir ? (Direction)e->direction : dir, 1);
    return 1;
}

