    if (e->collision_group != ACTOR_GROUP_PICKUP || e->pickup_collected ||
        !script || script->op == SCRIPT_END) return 0;
    e->pickup_collected = 1;
    if (world_run_script(script)) return 1;
    e->pickup_collected = 0;
