export type IconName = keyof typeof ICONS;

export default function Icon({ name, size = 12, className }: { name: IconName; size?: number; className?: string }) {
  const rows = ICONS[name];
  let d = "";
  rows.forEach((row, y) => {
    // One path segment per horizontal run of pixels.
    let x = 0;
    while (x < row.length) {
      if (row[x] !== "#") {
        x++;
        continue;
      }
      const start = x;
      while (x < row.length && row[x] === "#") x++;
      d += `M${start} ${y}h${x - start}v1h${start - x}z`;
    }
  });
  return (
    <svg
      className={className}
      width={size}
      height={size}
      viewBox="0 0 12 12"
      shapeRendering="crispEdges"
      aria-hidden
      style={{ display: "inline-block", verticalAlign: "-2px", flex: "none" }}
    >
      <path d={d} fill="currentColor" />
    </svg>
  );
}
